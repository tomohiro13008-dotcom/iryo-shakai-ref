def main():
    print("| 用途 | 前 | 後ろ | 比 | 基準 | 判定 |")
    print("| --- | --- | --- | --- | --- | --- |")
    bad = 0
    for kind, rows, need in (("文字", TEXT, 4.5), ("枠", LINES, 3.0)):
        for name, fg, bg in rows:
            r = ratio(fg, bg)
            okk = r >= need
            bad += not okk
            print(f"| {name} | `{fg}` | `{bg}` | {r:.2f}:1 | {kind} {need}:1 | {'○' if okk else '×'} |")
    print(f"\n不合格 {bad} 件")


if __name__ == "__main__":
    main()
